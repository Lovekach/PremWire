def source_detail_instruction(source_text: str) -> str:
    cleaned = re.sub(r"(?:https?://|www\.)\S+", " ", source_text)
    cleaned = re.sub(r"\s+", " ", cleaned).strip()
    length = len(cleaned)
    if length < 180:
        return (
            "Исходник короткий. Напиши одно-два содержательных предложения в одном "
            "или двух коротких абзацах. Не добавляй фон и не задавай вопросов аудитории."
        )
    if length < 450:
        return (
            "Исходник среднего объёма. Напиши два-четыре предложения в двух коротких "
            "абзацах. Не добавляй вопросов аудитории."
        )
    return (
        "Исходник подробный. Напиши четыре-шесть предложений в трёх коротких абзацах, "
        "сохранив все важные подтверждённые детали без новых фактов."
    )


@dataclass(frozen=True, slots=True)
class DraftPacket:
    item_id: int
    source_text: str
    source_url: str
    source_name: str
    prompt: str

    def save(self, directory: Path) -> Path:
        directory.mkdir(parents=True, exist_ok=True)
        path = directory / f"item-{self.item_id}.json"
        path.write_text(
            json.dumps(
                {
                    "item_id": self.item_id,
                    "source_name": self.source_name,
                    "source_url": self.source_url,
                    "source_text": self.source_text,
                    "prompt": self.prompt,
                },
                ensure_ascii=False,
                indent=2,
            ),
            encoding="utf-8",
        )
        return path


